"""Live checks of the Python package against the real Datadog Log Management API (GRO-1385).

Service-owned (not generated by sdk-kit). It covers what the Docker suite cannot: the functions
listed as SaaS-only in ``docs/compatibility.md``. It sends logs with a unique marker through the
intake, reads them back through the Logs Search API (``wait_for_log``, ``search_logs``,
``iterate_logs``, ``search``, ``aggregate_logs``) and checks ``validate_api_key`` and
``list_indexes`` with real keys.

Environment (the same names as the GitHub organisation secrets):

    DATADOG_API_KEY   API key of the Datadog organisation used for live checks (required)
    DATADOG_APP_KEY   application key with logs_read_data and logs_read_config (required)
    DATADOG_SITE      Datadog site, default datadoghq.eu
    LIVE_TIMEOUT_S    how long to wait for a log to become searchable, default 300

Without the two keys it prints ``skipped: no credentials`` and exits 0. Run it with
``make -C live live`` (installs ``./python`` into ``live/.venv``) or, with the package
installed, ``python live/live_test.py``. ``--check-credentials`` only reports whether the keys
are set (exit 0) or not (exit 78) and never imports the SDK.
"""

from __future__ import annotations

import os
import sys
import time
import uuid
from collections.abc import Callable, Iterable, Mapping
from typing import Any

REQUIRED_ENV = ("DATADOG_API_KEY", "DATADOG_APP_KEY")
DEFAULT_SITE = "datadoghq.eu"
SERVICE = "grow-sdk-live-python"
LIVE_ENV = "live"
EXIT_SKIPPED = 78  # EX_CONFIG: only used by --check-credentials


# --------------------------------------------------------------------------- harness


class CheckFailedError(AssertionError):
    """An expectation of a live check did not hold."""


def expect(condition: object, message: str) -> None:
    """Raise :class:`CheckFailedError` with ``message`` unless ``condition`` is truthy."""
    if not condition:
        raise CheckFailedError(message)


def poll(fn: Callable[[], Any], *, timeout_s: float, interval_s: float, what: str) -> Any:
    """Call ``fn`` until it returns a truthy value; builtin ``TimeoutError`` at the deadline."""
    deadline = time.monotonic() + timeout_s
    while True:
        value = fn()
        if value:
            return value
        if time.monotonic() + interval_s > deadline:
            raise TimeoutError(f"{what}: not seen within {timeout_s:.0f} s")
        time.sleep(interval_s)


def _annotation(text: str) -> str:
    return text.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")


class Suite:
    """Runs named checks in order and records PASS, FAIL, WARN or SKIP for each."""

    def __init__(self, title: str) -> None:
        self.title = title
        self.results: list[tuple[str, str, str]] = []
        self.passed: set[str] = set()
        self.github = os.environ.get("GITHUB_ACTIONS") == "true"

    def check(
        self,
        name: str,
        fn: Callable[[], Any],
        *,
        needs: Iterable[str] = (),
        warn_only: bool = False,
    ) -> Any:
        """Run ``fn``; a check whose ``needs`` did not pass is skipped. Returns ``fn()``."""
        missing = [n for n in needs if n not in self.passed]
        if missing:
            self._record("SKIP", name, "needs " + ", ".join(missing))
            return None
        started = time.monotonic()
        try:
            value = fn()
        except Exception as err:  # noqa: BLE001 - every failure is reported, the suite goes on
            status = "WARN" if warn_only else "FAIL"
            self._record(status, name, f"{type(err).__name__}: {err}")
            return None
        self.passed.add(name)
        self._record("PASS", name, f"{time.monotonic() - started:.1f} s")
        return value

    def _record(self, status: str, name: str, detail: str) -> None:
        self.results.append((status, name, detail))
        print(f"{status:4} {name} ({detail})", flush=True)
        if self.github and status in ("FAIL", "WARN"):
            level = "error" if status == "FAIL" else "warning"
            print(f"::{level} title=live: {_annotation(name)}::{_annotation(detail)}", flush=True)

    def finish(self) -> int:
        """Print the summary (and the GitHub step summary); 1 when a check failed."""
        counts = {s: sum(1 for r in self.results if r[0] == s) for s in ("PASS", "FAIL", "WARN")}
        counts["SKIP"] = len(self.results) - sum(counts.values())
        line = ", ".join(f"{n} {s.lower()}" for s, n in counts.items())
        print(f"\n{self.title}: {line}", flush=True)
        summary = os.environ.get("GITHUB_STEP_SUMMARY")
        if summary:
            rows = "\n".join(f"| {s} | {n} | {d.replace('|', '/')} |" for s, n, d in self.results)
            with open(summary, "a", encoding="utf-8") as fh:
                fh.write(f"### {self.title}\n\n{line}\n\n| Result | Check | Detail |\n")
                fh.write(f"| - | - | - |\n{rows}\n\n")
        return 1 if counts["FAIL"] else 0


def info(text: str) -> None:
    """An informational line under the current check."""
    print(f"     {text}", flush=True)


def missing_credentials(environ: Mapping[str, str]) -> list[str]:
    """Names of the required variables that are unset or empty."""
    return [name for name in REQUIRED_ENV if not environ.get(name, "").strip()]


# --------------------------------------------------------------------------- live checks


def run() -> int:
    """All live checks; returns the exit code."""
    import grow_datadog_logs as sdk

    site = os.environ.get("DATADOG_SITE", "").strip() or DEFAULT_SITE
    timeout_s = float(os.environ.get("LIVE_TIMEOUT_S", "") or 300)
    marker = f"growlive{uuid.uuid4().hex[:16]}"
    run_tag = f"grow_live_run:{marker}"
    environ = {
        "DD_API_KEY": os.environ["DATADOG_API_KEY"].strip(),
        "DD_APP_KEY": os.environ["DATADOG_APP_KEY"].strip(),
        "DD_SITE": site,
        # GROW_DATADOG_LOGS_* (e.g. _INTAKE_URL / _API_URL) pass through, to aim at a proxy.
        **{k: v for k, v in os.environ.items() if k.startswith("GROW_DATADOG_LOGS_")},
    }
    suite = Suite(f"datadog-logs live checks (Python {sdk.__version__}, site {site})")
    print(f"marker {marker}, service {SERVICE}, env {LIVE_ENV}\n", flush=True)
    state: dict[str, Any] = {}

    def build() -> None:
        config = sdk.DatadogLogsConfig.from_env(
            environ, service=SERVICE, env=LIVE_ENV, tags=[run_tag, "suite:grow-sdk-live"]
        )
        info(f"intake {config.intake_url}, api {config.api_url}")
        state["client"] = sdk.DatadogLogsClient(config)

    suite.check("config + client", build)
    client: Any = state.get("client")
    if client is None:
        return suite.finish()

    with client:

        def health() -> None:
            status = client.health()
            info(f"{status.status} {dict(status.details)}")
            expect(status.healthy, f"health() not healthy: {status}")

        def ping() -> None:
            info(f"{client.ping():.0f} ms")

        def validate() -> None:
            expect(client.validate_api_key() is True, "validate_api_key() returned False")

        def validate_wrong() -> None:
            bad = sdk.DatadogLogsConfig.from_env({**environ, "DD_API_KEY": "0" * 32})
            with sdk.DatadogLogsClient(bad) as other:
                expect(other.validate_api_key() is False, "a wrong key was reported valid")

        def server_version() -> None:
            try:
                client.server_version()
            except sdk.UnsupportedError:
                return
            raise CheckFailedError("server_version() did not raise UnsupportedError")

        suite.check("health", health)
        suite.check("ping", ping)
        suite.check("validate_api_key (real key)", validate)
        suite.check("validate_api_key (wrong key -> False)", validate_wrong)
        suite.check("server_version -> UNSUPPORTED", server_version)

        def send() -> None:
            state["sent_at"] = time.monotonic()
            logs = client.log_client()
            log = logs.logger("grow.live", {"grow.live.marker": marker})
            log.info(f"{marker} info record", {"grow.live.kind": "info"})
            log.warn(f"{marker} warn record", {"grow.live.kind": "warn"})
            log.error(f"{marker} error record", {"grow.live.kind": "error"})
            logs.flush(60)
            stats = logs.stats()
            info(f"log client: {stats}")
            expect(stats.sent >= 3, f"log client sent {stats.sent} of 3")
            expect(stats.failed == 0 and stats.dropped == 0, f"log client lost records: {stats}")
            record = sdk.LogRecord(
                body=f"{marker} exporter record",
                severity=sdk.Severity.INFO,
                attributes={"grow.live.marker": marker, "grow.live.kind": "exporter"},
                resource={"service.name": SERVICE, "deployment.environment": LIVE_ENV},
            )
            result = client.exporter.export([record])
            expect(
                result.accepted == 1 and result.error is None,
                f"exporter.export: {result}",
            )

        suite.check("send 4 logs (log client + exporter)", send)

        def query() -> None:
            state["query"] = client.query()

        suite.check("query client", query)
        q: Any = state.get("query")

        def wait_for_log() -> None:
            record = q.wait_for_log(f'"{marker}"', timeout_s=timeout_s, interval_s=5)
            delay = time.monotonic() - state["sent_at"]
            info(f"searchable after {delay:.0f} s: {record.body!r} [{record.severity_text}]")
            expect(marker in record.body, f"wait_for_log returned {record.body!r}")

        sent = ["send 4 logs (log client + exporter)", "query client"]
        suite.check("wait_for_log (marker in the message)", wait_for_log, needs=sent)
        found = [*sent, "wait_for_log (marker in the message)"]

        def search_logs() -> None:
            def page() -> Any:
                result = q.search_logs(run_tag, from_="now-30m", limit=100)
                return result if len(result.events) >= 4 else None

            result = poll(page, timeout_s=180, interval_s=10, what="4 logs by tag")
            events = result.events
            info(f"{len(events)} events, statuses {sorted({e.status or '' for e in events})}")
            expect(len(events) == 4, f"expected 4 events, got {len(events)}")
            expect(all(marker in e.message for e in events), "an event lost the marker")
            expect(all(e.service == SERVICE for e in events), "an event has another service")
            expect(all(f"env:{LIVE_ENV}" in e.tags for e in events), "env tag missing")

        suite.check("search_logs (by tag, all 4)", search_logs, needs=found)

        def iterate_logs() -> None:
            events = list(q.iterate_logs(run_tag, from_="now-30m", limit=4, page_size=2))
            ids = {e.id for e in events}
            expect(len(events) == 4 and len(ids) == 4, f"{len(events)} events, {len(ids)} ids")

        suite.check("iterate_logs (cursor paging, 2 per page)", iterate_logs, needs=found)

        def search() -> None:
            result = q.search(f'"{marker}"', limit=10)
            expect(result.records, "search() returned no records")
            expect(all(marker in r.body for r in result.records), "a record lost the marker")

        suite.check("search (category API)", search, needs=found)

        def aggregate() -> None:
            def counted() -> Any:
                result = q.aggregate_logs(
                    sdk.DatadogCompute("count"),
                    [sdk.DatadogGroupBy("status")],
                    query=run_tag,
                    from_="now-30m",
                )
                total = sum(b.number("c0") or 0 for b in result.buckets)
                return result if total >= 4 else None

            result = poll(counted, timeout_s=180, interval_s=10, what="aggregate count 4")
            info(", ".join(f"{b.by.get('status')}={b.number('c0'):.0f}" for b in result.buckets))

        suite.check("aggregate_logs (count by status)", aggregate, needs=found)

        def list_indexes() -> None:
            indexes = q.list_indexes()
            info(", ".join(f"{i.name} ({i.retention_days} d)" for i in indexes))
            expect(indexes, "list_indexes() returned no index")
            expect(q.list_streams() == [i.name for i in indexes], "list_streams != index names")

        suite.check("list_indexes + list_streams", list_indexes, needs=["query client"])

        def list_labels() -> None:
            try:
                q.list_labels()
            except sdk.UnsupportedError:
                return
            raise CheckFailedError("list_labels() did not raise UnsupportedError")

        suite.check("list_labels -> UNSUPPORTED", list_labels, needs=["query client"])

    return suite.finish()


def main(argv: list[str]) -> int:
    missing = missing_credentials(os.environ)
    if missing:
        print(f"skipped: no credentials ({', '.join(missing)} not set); live checks not run")
        return EXIT_SKIPPED if "--check-credentials" in argv else 0
    if "--check-credentials" in argv:
        print("credentials: set")
        return 0
    return run()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
